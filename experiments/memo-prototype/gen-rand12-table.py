#!/usr/bin/env python3
"""
Convert captures/rand12.csv (header X1..X12,out ; 4096 full-enumeration rows)
into captures/rand12-table.metta, an (= (rand12Table) (mkITable <rows> <labels>))
literal in the same flat-list-literal shape used by common/reference-formulas.metta's
(miniTable) (NOT the cons-nested-construction shape used by common/truth-tables.metta
-- both shapes reduce to the identical flat expression once (majority3Table) etc. is
called, since `cons` is a grounded builtin that gets reduced bottom-up; the flat-literal
shape is just fewer characters and needs no reduction at all).

Usage:
    python3 experiments/memo-prototype/gen-rand12-table.py \
        experiments/memo-prototype/captures/rand12.csv \
        experiments/memo-prototype/captures/rand12-table.metta
"""

import csv
import sys


def bool_word(cell):
    return "True" if cell.strip() in ("1", "True", "true") else "False"


def main():
    if len(sys.argv) != 3:
        print("usage: gen-rand12-table.py <in.csv> <out.metta>", file=sys.stderr)
        sys.exit(1)
    in_csv, out_metta = sys.argv[1], sys.argv[2]

    with open(in_csv, newline="") as f:
        reader = csv.reader(f)
        header = next(reader)
        rows = list(reader)

    # header is X1..X12,out -- target column last, renamed Out to match the
    # capitalization convention in common/truth-tables.metta.
    labels = [h if h != "out" else "Out" for h in header]

    row_lines = []
    for row in rows:
        cells = " ".join(bool_word(c) for c in row)
        row_lines.append("    (" + cells + ")")

    with open(out_metta, "w") as f:
        f.write(
            ";; ---------------------------------------------------------------------------\n"
            ";; AUTO-GENERATED by gen-rand12-table.py from captures/rand12.csv -- do not\n"
            ";; edit by hand. Same mkITable shape as common/truth-tables.metta (row-major,\n"
            ";; target column Out LAST), but written as flat list literals (like\n"
            ";; common/reference-formulas.metta's miniTable) since these are already-flat\n"
            ";; boolean tuples needing no cons-based construction/reduction.\n"
            f";; {len(rows)} rows x {len(labels)} labels (full 2**12 enumeration).\n"
            ";; ---------------------------------------------------------------------------\n\n"
            "(= (rand12Table) (mkITable\n"
            "   (\n"
            + "\n".join(row_lines)
            + "\n   )\n"
            "   (" + " ".join(labels) + ")))\n"
        )
    print(f"wrote {out_metta}: {len(rows)} rows, labels={labels}")


if __name__ == "__main__":
    main()
